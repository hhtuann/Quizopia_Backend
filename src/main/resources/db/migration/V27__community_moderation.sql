-- =====================================================================
-- V27 (community moderation, ADR-006 §3 V27 / §5 / §7, issue #42):
--
--   * community_reports             — publication reports with the
--                                     one-OPEN-per-reporter invariant
--                                     (partial unique index)
--   * community_moderation_actions  — append-only moderation audit
--                                     trail (HIDE/RESTORE, report
--                                     dismiss/resolve, moderator
--                                     grant/revoke journal)
--
-- V1–V26 are untouched; this migration only ADDS tables and indexes.
-- FK policy (ADR-006 §3): community_reports.publication_id CASCADEs
-- (the report's meaning dies with the publication); every FK to users
-- is ON DELETE RESTRICT (no user hard-delete path exists).
--
-- No seed rows: COMMUNITY_MODERATOR stays dormant — moderator power is
-- granted ONLY by the operator runbook
-- (docs/runbooks/community-moderator-provisioning.md, ADR-006 §5);
-- no API may grant or revoke it.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. COMMUNITY_REPORTS
--    status OPEN → DISMISSED | RESOLVED (moderator transitions only).
--    The partial unique index enforces "at most one OPEN report per
--    (reporter, publication)": re-reporting after a handled report is a
--    NEW OPEN row; concurrent duplicate submissions collapse via
--    INSERT … ON CONFLICT … DO NOTHING (§7 fixed order).
-- ---------------------------------------------------------------------
CREATE TABLE community_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    publication_id BIGINT NOT NULL,
    reporter_user_id BIGINT NOT NULL,

    reason_code VARCHAR(40) NOT NULL,
    details VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    handled_by BIGINT,
    handled_at TIMESTAMPTZ,
    resolution_note VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_community_reports_publication
        FOREIGN KEY (publication_id) REFERENCES community_publications (id) ON DELETE CASCADE,
    CONSTRAINT fk_community_reports_reporter
        FOREIGN KEY (reporter_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_reports_handled_by
        FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE RESTRICT,

    CONSTRAINT chk_community_reports_reason_code
        CHECK (reason_code IN ('INAPPROPRIATE_CONTENT', 'COPYRIGHT', 'MISLEADING', 'SPAM', 'OTHER')),
    CONSTRAINT chk_community_reports_status
        CHECK (status IN ('OPEN', 'DISMISSED', 'RESOLVED'))
);

-- One OPEN report per (reporter, publication) — the dedupe oracle.
CREATE UNIQUE INDEX uk_community_reports_open_per_reporter
    ON community_reports (reporter_user_id, publication_id)
    WHERE status = 'OPEN';

-- Moderator queue scan (status filter + newest-first).
CREATE INDEX idx_community_reports_status_created
    ON community_reports (status, created_at);

-- openReportCount / per-publication drill-down.
CREATE INDEX idx_community_reports_publication
    ON community_reports (publication_id);

-- ---------------------------------------------------------------------
-- 2. COMMUNITY_MODERATION_ACTIONS (append-only audit, ADR-006 §5/§57)
--    Every moderation transition appends exactly one row:
--    HIDE / RESTORE carry the publication states, REPORT_DISMISS /
--    REPORT_RESOLVE carry the report id, MODERATOR_GRANTED /
--    MODERATOR_REVOKED are written by the OPERATOR runbook with the
--    dedicated operator account as actor. The application repository
--    exposes save + reads only — there is no update/delete surface.
-- ---------------------------------------------------------------------
CREATE TABLE community_moderation_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_user_id BIGINT NOT NULL,
    publication_id BIGINT,
    report_id BIGINT,

    action VARCHAR(40) NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20),
    from_moderation_state VARCHAR(20),
    to_moderation_state VARCHAR(20),
    reason VARCHAR(500) NOT NULL,
    correlation_id VARCHAR(64),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_community_moderation_actions_actor
        FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_moderation_actions_publication
        FOREIGN KEY (publication_id) REFERENCES community_publications (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_moderation_actions_report
        FOREIGN KEY (report_id) REFERENCES community_reports (id) ON DELETE RESTRICT,

    CONSTRAINT chk_community_moderation_actions_action
        CHECK (action IN ('HIDE', 'RESTORE', 'REPORT_DISMISS', 'REPORT_RESOLVE',
                          'MODERATOR_GRANTED', 'MODERATOR_REVOKED')),
    CONSTRAINT chk_community_moderation_actions_from_status
        CHECK (from_status IS NULL OR from_status IN ('UNPUBLISHED', 'PUBLISHED')),
    CONSTRAINT chk_community_moderation_actions_to_status
        CHECK (to_status IS NULL OR to_status IN ('UNPUBLISHED', 'PUBLISHED')),
    CONSTRAINT chk_community_moderation_actions_from_state
        CHECK (from_moderation_state IS NULL OR from_moderation_state IN ('VISIBLE', 'HIDDEN')),
    CONSTRAINT chk_community_moderation_actions_to_state
        CHECK (to_moderation_state IS NULL OR to_moderation_state IN ('VISIBLE', 'HIDDEN'))
);

-- Per-publication history (newest-first).
CREATE INDEX idx_community_moderation_actions_publication
    ON community_moderation_actions (publication_id, created_at DESC);

-- Report-driven audit lookup.
CREATE INDEX idx_community_moderation_actions_report
    ON community_moderation_actions (report_id);

-- ---------------------------------------------------------------------
-- 3. Verification — the moderation contract holds.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE indexname = 'uk_community_reports_open_per_reporter'
    ) THEN
        RAISE EXCEPTION 'V27 verification: partial unique OPEN-report index missing';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE indexname = 'idx_community_moderation_actions_publication'
    ) THEN
        RAISE EXCEPTION 'V27 verification: moderation audit publication index missing';
    END IF;
    RAISE NOTICE 'V27: community moderation tables complete';
END $$;
