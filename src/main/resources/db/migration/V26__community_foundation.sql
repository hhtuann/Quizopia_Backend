-- =====================================================================
-- V26 (community foundation, ADR-006 §3, issue #40):
--
--   * community_categories        — migration-managed taxonomy (seeded
--                                   once from the V24 subject catalog,
--                                   deduplicated by code; no CRUD API)
--   * community_publications      — the publication aggregate (one row
--                                   per exam, owner lifecycle only)
--   * community_tags              — on-demand label pool (unique ci)
--   * community_publication_tags  — publication↔tag links (≤5 per
--                                   publication, app-enforced)
--   * community_rate_buckets     — generalized V23 abuse-bucket shape
--                                   backing CommunityRateLimiter (§9)
--   * RBAC seeds                  — COMMUNITY_* permissions, dormant
--                                   COMMUNITY_MODERATOR role (granted
--                                   to nobody by this migration)
--
-- V1–V25 are untouched; this migration only ADDS tables and seed rows.
-- FK policy (ADR-006 §3): every FK to users/exams is ON DELETE RESTRICT;
-- publication_tag rows cascade from both parents.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. COMMUNITY_CATEGORIES
--    Migration-managed catalog (like exam_purposes): read-only for the
--    application, never deleted, so publications may reference it with
--    ON DELETE RESTRICT confidence. Seeded once below from the ACTIVE
--    V24 subject catalog deduplicated by code (subjects are per-grade;
--    e.g. TOAN exists once per grade level — one category per code).
-- ---------------------------------------------------------------------
CREATE TABLE community_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(40) NOT NULL,
    title VARCHAR(100) NOT NULL,
    position INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uk_community_categories_code_ci
    ON community_categories (LOWER(code));

INSERT INTO community_categories (code, title, position)
SELECT code, name, rn FROM (
  SELECT DISTINCT ON (LOWER(s.code)) LOWER(s.code) AS code, s.name, s.id,
         dense_rank() OVER (ORDER BY LOWER(s.code)) AS rn
  FROM subjects s WHERE s.status = 'ACTIVE'
  ORDER BY LOWER(s.code), s.id
) t;

-- ---------------------------------------------------------------------
-- 2. COMMUNITY_PUBLICATIONS
--    One publication per PUBLISHED exam (exam_id UNIQUE, immutable —
--    no setter, no UPDATE path writes it). publisher_user_id is the
--    owning teacher (== exams.created_by_user_id, rechecked at every
--    state change, never updated). status/moderation_state/reuse_policy
--    are CHECK-constrained enums; `version` is the JPA optimistic token
--    (owner PATCH/publish concurrency). Denormalized counts come from
--    the immutable published composition via ExamCommunityPort.
-- ---------------------------------------------------------------------
CREATE TABLE community_publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    exam_id BIGINT NOT NULL,
    publisher_user_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL,
    moderation_state VARCHAR(20) NOT NULL,
    reuse_policy VARCHAR(20) NOT NULL DEFAULT 'NO_FORK',

    title VARCHAR(255) NOT NULL,
    summary VARCHAR(500),
    author_alias VARCHAR(80),
    category_id BIGINT,

    question_count INT NOT NULL DEFAULT 0,
    section_count INT NOT NULL DEFAULT 0,
    duration_minutes INT NOT NULL DEFAULT 0,
    published_at TIMESTAMPTZ,

    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_community_publications_exam UNIQUE (exam_id),

    CONSTRAINT fk_community_publications_exam
        FOREIGN KEY (exam_id) REFERENCES exams (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_publications_publisher
        FOREIGN KEY (publisher_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_publications_category
        FOREIGN KEY (category_id) REFERENCES community_categories (id) ON DELETE RESTRICT,

    CONSTRAINT chk_community_publications_status
        CHECK (status IN ('UNPUBLISHED', 'PUBLISHED')),
    CONSTRAINT chk_community_publications_moderation_state
        CHECK (moderation_state IN ('VISIBLE', 'HIDDEN')),
    CONSTRAINT chk_community_publications_reuse_policy
        CHECK (reuse_policy IN ('NO_FORK', 'ALLOW_FORK'))
);

-- Public catalog scan (visibility predicate columns first; §4/#41).
CREATE INDEX idx_community_publications_catalog
    ON community_publications (status, moderation_state, published_at DESC, id DESC);

-- Owner list (/api/community/me/publications).
CREATE INDEX idx_community_publications_owner
    ON community_publications (publisher_user_id, created_at DESC, id DESC);

-- ---------------------------------------------------------------------
-- 3. COMMUNITY_TAGS + COMMUNITY_PUBLICATION_TAGS
--    Labels are created on demand from create/PATCH payloads (already
--    lower-cased/trimmed by the service, [a-z0-9][a-z0-9 -]{0,39}, ≤5
--    distinct per publication) via INSERT … ON CONFLICT DO NOTHING —
--    a caught constraint violation would abort the enclosing PostgreSQL
--    transaction (roster-membership precedent). tag_id is indexed for
--    tag-driven semi-joins and usage counts (#41).
-- ---------------------------------------------------------------------
CREATE TABLE community_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    label VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uk_community_tags_label_ci
    ON community_tags (LOWER(label));

CREATE TABLE community_publication_tags (
    publication_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    PRIMARY KEY (publication_id, tag_id),

    CONSTRAINT fk_community_publication_tags_publication
        FOREIGN KEY (publication_id) REFERENCES community_publications (id) ON DELETE CASCADE,
    CONSTRAINT fk_community_publication_tags_tag
        FOREIGN KEY (tag_id) REFERENCES community_tags (id) ON DELETE CASCADE
);

CREATE INDEX idx_community_publication_tags_tag
    ON community_publication_tags (tag_id);

-- ---------------------------------------------------------------------
-- 4. COMMUNITY_RATE_BUCKETS
--    Generalized V23 password_reset_abuse_buckets shape (ADR-006 §9):
--    fixed 1-hour windows, saturating attempts, HMAC-SHA-256 keys
--    (64 lowercase hex, domain-separated `community:<dimension>:<value>`)
--    so the table never stores plaintext user ids or IPs. Upserted via
--    ON CONFLICT (bucket_key) DO NOTHING → SELECT … FOR UPDATE → UPDATE
--    by CommunityRateLimiter; admission FAILS CLOSED when the bucket
--    store is unavailable. Rows expire 2h after their window and are
--    swept by CommunityRateBucketCleanupScheduler.
-- ---------------------------------------------------------------------
CREATE TABLE community_rate_buckets (
    bucket_key VARCHAR(64) PRIMARY KEY,

    window_start TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL,
    last_admitted_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT chk_community_rate_buckets_key
        CHECK (bucket_key ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_community_rate_buckets_attempts
        CHECK (attempts BETWEEN 0 AND 2147483647),

    CONSTRAINT chk_community_rate_buckets_window
        CHECK (expires_at > window_start)
);

CREATE INDEX idx_community_rate_buckets_expires_at
    ON community_rate_buckets (expires_at);

-- ---------------------------------------------------------------------
-- 5. RBAC SEEDS (idempotent INSERT … WHERE NOT EXISTS)
--    COMMUNITY_PUBLISH / COMMUNITY_FORK            → TEACHER
--    COMMUNITY_REPORT / COMMUNITY_BOOKMARK         → STUDENT + TEACHER
--    dormant role COMMUNITY_MODERATOR (no user_roles grant here —
--    provisioning is operator-only, ADR-006 §5) with
--    COMMUNITY_MODERATION.
-- ---------------------------------------------------------------------
INSERT INTO permissions (code, name, description)
SELECT v.code, v.name, v.description
FROM (VALUES
    ('COMMUNITY_PUBLISH',
     'Publish to Community',
     'Create and manage own community publications (publish/unpublish a PUBLISHED exam the caller owns).'),
    ('COMMUNITY_FORK',
     'Fork Community Publication',
     'Fork a visible ALLOW_FORK community publication into an owned draft exam copy.'),
    ('COMMUNITY_REPORT',
     'Report Community Publication',
     'Submit reports on visible community publications.'),
    ('COMMUNITY_BOOKMARK',
     'Bookmark Community Publication',
     'Save and list bookmarks of visible community publications.'),
    ('COMMUNITY_MODERATION',
     'Moderate Community',
     'Operator-provisioned moderator capability: report queue, hide/restore, dismiss/resolve.')
) AS v(code, name, description)
WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = v.code);

INSERT INTO roles (code, name, description)
SELECT v.code, v.name, v.description
FROM (VALUES
    ('COMMUNITY_MODERATOR',
     'Community Moderator',
     'Dormant, operator-provisioned moderator grant (ADR-006 §5): report queue, hide/restore, dismiss/resolve. Granted to nobody by seed; user_roles is the only grant mechanism.')
) AS v(code, name, description)
WHERE NOT EXISTS (SELECT 1 FROM roles r WHERE r.code = v.code);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code IN ('COMMUNITY_PUBLISH', 'COMMUNITY_FORK',
                                 'COMMUNITY_REPORT', 'COMMUNITY_BOOKMARK')
WHERE r.code = 'TEACHER'
  AND NOT EXISTS (
      SELECT 1 FROM role_permissions rp
      WHERE rp.role_id = r.id AND rp.permission_id = p.id);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code IN ('COMMUNITY_REPORT', 'COMMUNITY_BOOKMARK')
WHERE r.code = 'STUDENT'
  AND NOT EXISTS (
      SELECT 1 FROM role_permissions rp
      WHERE rp.role_id = r.id AND rp.permission_id = p.id);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code = 'COMMUNITY_MODERATION'
WHERE r.code = 'COMMUNITY_MODERATOR'
  AND NOT EXISTS (
      SELECT 1 FROM role_permissions rp
      WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------------
-- 6. Verification — the foundation contract holds.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    -- Taxonomy: one row per distinct ACTIVE subject code, contiguous
    -- dense positions (leg-agnostic assertion, ADR-006 §3).
    IF (SELECT count(*) FROM community_categories)
       <> (SELECT count(DISTINCT LOWER(code)) FROM community_categories) THEN
        RAISE EXCEPTION 'V26 verification: community_categories has duplicate codes';
    END IF;
    IF EXISTS (
        SELECT 1 FROM (
            SELECT position, count(*) AS c FROM community_categories GROUP BY position
        ) g WHERE c > 1
    ) THEN
        RAISE EXCEPTION 'V26 verification: community_categories positions are not unique';
    END IF;
    IF (SELECT count(*) FROM community_categories)
       <> (SELECT coalesce(max(position), 0) FROM community_categories) THEN
        RAISE EXCEPTION 'V26 verification: community_categories positions are not contiguous';
    END IF;

    -- RBAC grants exactly as specified (dormant moderator role, no grants).
    IF (SELECT count(*) FROM role_permissions rp
        JOIN permissions p ON p.id = rp.permission_id
        WHERE p.code LIKE 'COMMUNITY_%') <> 7 THEN
        RAISE EXCEPTION 'V26 verification: expected exactly 7 COMMUNITY_* role grants';
    END IF;
    IF EXISTS (
        SELECT 1 FROM user_roles ur
        JOIN roles r ON r.id = ur.role_id
        WHERE r.code = 'COMMUNITY_MODERATOR'
    ) THEN
        RAISE EXCEPTION 'V26 verification: COMMUNITY_MODERATOR must ship dormant (no user grants)';
    END IF;

    RAISE NOTICE 'V26: community foundation complete (categories: %)',
        (SELECT count(*) FROM community_categories);
END $$;
