-- =====================================================================
-- V33 (P4-A1 monitoring foundation, issue #80, ADR-008 D1/D4/D5/D7):
--
-- Per-session Exam Monitoring policy, 1:1 with exam_sessions.
--
-- Invariants (enforced in SessionMonitoringPolicyService + tests):
--   * Monitoring is OFF by default; every boolean flag defaults to
--     FALSE. Sessions created before P4-A have NO row here — the read
--     path treats a missing row as the all-OFF legacy policy, so
--     existing sessions are unchanged (issue #80 regression gate).
--   * camera_required is NOT a column: it is a derived enforced
--     property of monitoring_enabled=true (ADR-008 invariant 2), so a
--     contradictory persisted state cannot exist.
--   * Freeze is NOT a persisted flag: it is derived at write time from
--     (status, startsAt, attempt existence) under the session row lock
--     (ADR-008 invariant 3). No frozen_at column can go stale.
--   * Valid combinations (validated server-side, never trusted from
--     the client): ai_detection / activity_tracking / full_recording /
--     evidence_clips each require monitoring_enabled;
--     evidence_snapshots requires ai_detection; evidence_clips
--     requires full_recording (P4-A has no rolling-buffer capability —
--     P4-D extends).
--   * Retention (ADR-008 D7): media/evidence 30 days, activity
--     metadata 90 days. Stored as columns so P4-D cleanup jobs have a
--     per-session source of truth; NOT teacher-configurable in P4-A.
--
-- Forward-only: new table only, no changes to existing tables.
-- =====================================================================

CREATE TABLE session_monitoring_policies (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_id           BIGINT       NOT NULL,
    monitoring_enabled        BOOLEAN      NOT NULL DEFAULT FALSE,
    ai_detection_enabled      BOOLEAN      NOT NULL DEFAULT FALSE,
    activity_tracking_enabled BOOLEAN      NOT NULL DEFAULT FALSE,
    evidence_snapshots_enabled BOOLEAN     NOT NULL DEFAULT FALSE,
    full_recording_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,
    evidence_clips_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,
    media_retention_days      INTEGER      NOT NULL DEFAULT 30,
    activity_retention_days   INTEGER      NOT NULL DEFAULT 90,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_session_monitoring_policies_session
        FOREIGN KEY (exam_session_id) REFERENCES exam_sessions(id) ON DELETE CASCADE,
    CONSTRAINT uk_session_monitoring_policies_session UNIQUE (exam_session_id),
    CONSTRAINT chk_smp_retention_media CHECK (media_retention_days BETWEEN 1 AND 3650),
    CONSTRAINT chk_smp_retention_activity CHECK (activity_retention_days BETWEEN 1 AND 3650)
);

COMMENT ON TABLE session_monitoring_policies IS
    'P4-A1 (#80): per-session exam monitoring policy; 1:1 with exam_sessions; missing row = legacy all-OFF policy.';

-- ---------------------------------------------------------------------
-- Verification — policy table is empty on upgrade (no legacy session is
-- implicitly monitored) and the defaults are all-OFF.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF (SELECT COUNT(*) FROM session_monitoring_policies) <> 0 THEN
        RAISE EXCEPTION 'V33 verification failed: policy rows must not be backfilled';
    END IF;
END $$;
