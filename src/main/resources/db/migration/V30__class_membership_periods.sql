-- ============================================================
-- Quizopia Flyway Migration V30
-- Purpose: CLASS-M3 (issue #54) — historical membership attribution.
--   - classroom_membership_periods: temporal membership history
--     (one row per membership epoch; open period = current member).
--   - Triggers on classroom_members INSERT/DELETE maintain the history
--     atomically with every membership write path (direct add, invitation
--     accept, verified-email reconciliation, teacher remove, learner
--     leave/decline, teacher revoke, demo seeder — all funnel through
--     INSERT or DELETE on classroom_members).
--
-- Backfill policy (issue #54 design gate 4): only CURRENT members are
-- backfilled, joined_at = classroom_members.added_at (the only reliable
-- evidence). Pre-migration departed memberships are NOT fabricated.
--
-- Do not modify V1–V29. Do not modify this file after it has been applied.
-- ============================================================

-- 1. MEMBERSHIP PERIODS (temporal history)
CREATE TABLE classroom_membership_periods (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id  BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    joined_at     TIMESTAMPTZ  NOT NULL,
    left_at       TIMESTAMPTZ,
    CONSTRAINT fk_cmp_classroom
        FOREIGN KEY (classroom_id) REFERENCES classrooms(id) ON DELETE CASCADE,
    CONSTRAINT fk_cmp_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_cmp_interval CHECK (left_at IS NULL OR left_at > joined_at)
);

-- At most one OPEN period per (classroom, user): a new epoch can only open
-- after the previous one closed. Together with the single-writer trigger
-- discipline this makes overlapping closed periods impossible by construction.
CREATE UNIQUE INDEX uk_cmp_one_open
    ON classroom_membership_periods (classroom_id, user_id) WHERE left_at IS NULL;

-- Cohort lookups: members of a class over a time interval.
CREATE INDEX idx_cmp_cohort
    ON classroom_membership_periods (classroom_id, user_id, joined_at);

-- 2. BACKFILL — current members only (honest evidence; see header).
INSERT INTO classroom_membership_periods (classroom_id, user_id, joined_at, left_at)
SELECT cm.classroom_id, cm.user_id, cm.added_at, NULL
FROM classroom_members cm;

-- 3. HISTORY MAINTENANCE TRIGGERS
CREATE OR REPLACE FUNCTION classroom_membership_periods_write() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    v_joined TIMESTAMPTZ;
    v_last_left TIMESTAMPTZ;
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- joined_at honors the live row's added_at (the honest join
        -- evidence) but never starts before the previous epoch closed —
        -- under app-clock/DB-clock skew the clamp keeps epochs strictly
        -- ordered without violating chk_cmp_interval.
        SELECT MAX(left_at) INTO v_last_left
          FROM classroom_membership_periods
         WHERE classroom_id = NEW.classroom_id AND user_id = NEW.user_id;
        v_joined := GREATEST(COALESCE(NEW.added_at, now()),
                             COALESCE(v_last_left, '-infinity'::timestamptz)
                                 + '1 microsecond'::interval);
        -- Defensive no-op if an open period already exists (unreachable
        -- while uk_classroom_members_classroom_user holds).
        IF NOT EXISTS (SELECT 1 FROM classroom_membership_periods p
                       WHERE p.classroom_id = NEW.classroom_id
                         AND p.user_id = NEW.user_id
                         AND p.left_at IS NULL) THEN
            INSERT INTO classroom_membership_periods (classroom_id, user_id, joined_at, left_at)
            VALUES (NEW.classroom_id, NEW.user_id, v_joined, NULL);
        END IF;
        RETURN NEW;
    ELSE
        -- Close the open epoch. left_at must stay strictly after joined_at
        -- even under app-clock/DB-clock skew (joined_at can come from the
        -- application clock), so clamp to joined_at + 1us when needed.
        UPDATE classroom_membership_periods
           SET left_at = GREATEST(now(), joined_at + '1 microsecond'::interval)
         WHERE classroom_id = OLD.classroom_id
           AND user_id = OLD.user_id
           AND left_at IS NULL;
        IF NOT FOUND THEN
            -- Legacy row inserted before V30 and never touched since (or a
            -- defensive path): self-heal with a closed epoch anchored at the
            -- live row's own added_at — still honest evidence, same clamp.
            v_joined := COALESCE(OLD.added_at, now());
            INSERT INTO classroom_membership_periods (classroom_id, user_id, joined_at, left_at)
            VALUES (OLD.classroom_id, OLD.user_id, v_joined,
                    GREATEST(now(), v_joined + '1 microsecond'::interval));
        END IF;
        RETURN OLD;
    END IF;
END;
$fn$;

CREATE TRIGGER tg_classroom_members_hist_ins
    AFTER INSERT ON classroom_members
    FOR EACH ROW EXECUTE FUNCTION classroom_membership_periods_write();

CREATE TRIGGER tg_classroom_members_hist_del
    AFTER DELETE ON classroom_members
    FOR EACH ROW EXECUTE FUNCTION classroom_membership_periods_write();
