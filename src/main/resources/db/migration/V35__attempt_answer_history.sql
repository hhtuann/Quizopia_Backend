-- =====================================================================
-- V35 (P4-A3 atomic accepted-answer history, issue #82, ADR-008
-- invariant 7):
--
-- Exactly one history row per SERVER-ACCEPTED autosave sequence,
-- written in the SAME database transaction as the conditional UPSERT
-- in AttemptAnswerRepository.upsertIfNewer — and ONLY when that UPSERT
-- accepted (affected=1). Stale / retried / duplicate saves write ZERO
-- rows. A history-write failure rolls the whole autosave back
-- (answer mutation included).
--
--   * UNIQUE (attempt_id, attempt_question_id, accepted_sequence):
--     the atomicity witness — one accepted version per sequence.
--   * Composite ownership FK to attempt_questions(attempt_id, id)
--     mirrors attempt_answers; cross-attempt question ids are
--     rejected at the DB level.
--   * answer_payload: full canonical snapshot of the ACCEPTED payload.
--     Policy (ADR-008 invariant 7): every current question type
--     (SINGLE_CHOICE, MULTIPLE_CHOICE, TRUE_FALSE_MATRIX, NUMERIC_FILL)
--     is a small structured selection, so snapshots are bounded and
--         audit-faithful; NO essay/free-text type exists in P4-A. When a
--     free-text type is introduced, history MUST switch to hash-only
--     snapshots for those types (per-keystroke essay content is never
--     stored).
--   * accepted_at: the saved_at decided by the UPSERT (server clock).
--
-- Queryable by Attempt (PK-adjacent indexes), AttemptQuestion +
-- Sequence (the UNIQUE index) and server-accepted timestamp
-- (idx_aah_attempt_accepted).
--
-- Forward-only: new table only.
-- =====================================================================

CREATE TABLE attempt_answer_history (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id           BIGINT       NOT NULL,
    attempt_question_id  BIGINT       NOT NULL,
    accepted_sequence    BIGINT       NOT NULL,
    answer_payload       JSONB,
    accepted_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_attempt_answer_history_question
        FOREIGN KEY (attempt_id, attempt_question_id)
        REFERENCES attempt_questions(attempt_id, id) ON DELETE CASCADE,
    CONSTRAINT chk_aah_sequence CHECK (accepted_sequence >= 1),
    CONSTRAINT chk_aah_payload_object CHECK (answer_payload IS NULL OR jsonb_typeof(answer_payload) = 'object'),
    CONSTRAINT uk_attempt_answer_history_version
        UNIQUE (attempt_id, attempt_question_id, accepted_sequence)
);

COMMENT ON TABLE attempt_answer_history IS
    'P4-A3/#82: accepted-answer history — one row per server-accepted autosave sequence, written atomically with the UPSERT.';

-- Timeline/report ordering by server-accepted time within an attempt.
CREATE INDEX idx_aah_attempt_accepted
    ON attempt_answer_history (attempt_id, accepted_at, id);

-- ---------------------------------------------------------------------
-- Verification — history starts empty; accepted answers themselves are
-- NOT retroactively fabricated for pre-P4-A attempts.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF (SELECT COUNT(*) FROM attempt_answer_history) <> 0 THEN
        RAISE EXCEPTION 'V35 verification failed: history rows must not be backfilled';
    END IF;
END $$;
