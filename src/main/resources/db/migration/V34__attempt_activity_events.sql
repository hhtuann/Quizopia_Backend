-- =====================================================================
-- V34 (P4-A2/P4-A4 activity tracking + timeline, issues #81/#83,
-- ADR-008 invariants 8/15):
--
-- Durable append-only Attempt activity events — the unified timeline
-- read model. One row per event; both client-observed telemetry
-- (source CLIENT) and server-confirmed records (source SERVER) share
-- the table so the timeline is a single stable cursor-paged source.
--
--   * event_id: client- (or server-) supplied UUID, UNIQUE — the
--     idempotency identity; a retried batch re-inserts nothing
--     (ON CONFLICT DO NOTHING in the ingest path).
--   * Ordering/provenance: server_received_at (server clock, set by
--     the DB) + id tiebreaker is the stable chronological cursor.
--     client_occurred_at is stored VERBATIM (clock skew and
--     out-of-order delivery are retained, never "corrected" — the
--     client clock is not trusted, ADR-008 invariant 8).
--   * Browser events are observations, not verdicts: no misconduct
--     semantics live in the schema.
--   * metadata is bounded (ingest validates <=2KB serialized) and MUST
--     NOT carry answer payloads, tokens or secrets (ingest allowlist).
--   * event_type CHECK = the P4-A set ONLY. Camera/AI/recording types
--     (P4-B/C/D) require a new migration — fake media events cannot
--     be persisted in P4-A.
--   * No answer content columns: ANSWER_ACCEPTED metadata carries only
--     {attemptQuestionId, acceptedSequence}.
--
-- Includes monitoring_rate_buckets: PostgreSQL fixed-window admission
-- for the ingest endpoint (CommunityRateLimiter mechanics, ADR-006 §9
-- pattern, HMAC-hashed identities so no plaintext user ids stored).
--
-- Forward-only: new tables only.
-- =====================================================================

CREATE TABLE attempt_activity_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            UUID         NOT NULL,
    attempt_id          BIGINT       NOT NULL,
    event_type          VARCHAR(40)  NOT NULL,
    source              VARCHAR(10)  NOT NULL,
    client_occurred_at  TIMESTAMPTZ,
    client_sequence     BIGINT,
    client_instance_id  UUID,
    metadata            JSONB        NOT NULL DEFAULT '{}'::jsonb,
    server_received_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attempt_activity_events_attempt
        FOREIGN KEY (attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
    CONSTRAINT chk_aae_source CHECK (source IN ('CLIENT', 'SERVER')),
    CONSTRAINT chk_aae_client_source CHECK (
        source = 'SERVER'
        OR (client_occurred_at IS NOT NULL AND client_sequence IS NOT NULL)
    ),
    CONSTRAINT chk_aae_event_type CHECK (event_type IN (
        -- server-confirmed lifecycle
        'ATTEMPT_STARTED', 'ATTEMPT_RESUMED', 'ATTEMPT_SUBMITTED', 'ATTEMPT_TIMED_OUT',
        -- server-confirmed autosave acceptance
        'ANSWER_ACCEPTED',
        -- client-observed answer interactions
        'ANSWER_SELECTED', 'ANSWER_CHANGED', 'ANSWER_CLEARED',
        -- client-observed navigation/flags/autosave telemetry
        'QUESTION_NAVIGATED', 'QUESTION_FLAGGED', 'QUESTION_UNFLAGGED', 'AUTOSAVE_FAILED',
        -- client-observed browser telemetry
        'TAB_HIDDEN', 'TAB_VISIBLE', 'WINDOW_FOCUS_LOST', 'WINDOW_FOCUS_GAINED',
        'PAGE_RELOADED', 'CONNECTION_LOST', 'CONNECTION_RESTORED'
    )),
    CONSTRAINT chk_aae_metadata_object CHECK (jsonb_typeof(metadata) = 'object'),
    CONSTRAINT uk_attempt_activity_events_event_id UNIQUE (event_id)
);

COMMENT ON TABLE attempt_activity_events IS
    'P4-A2/#81 + P4-A4/#83: durable append-only attempt activity events (unified timeline read model).';

-- Timeline cursor: (attempt_id, server_received_at, id) ascending.
CREATE INDEX idx_aae_attempt_receipt
    ON attempt_activity_events (attempt_id, server_received_at, id);

-- Event-type filter within an attempt.
CREATE INDEX idx_aae_attempt_type
    ON attempt_activity_events (attempt_id, event_type, server_received_at);

-- Retention sweep support (activity_retention_days, P4-D).
CREATE INDEX idx_aae_received_at
    ON attempt_activity_events (server_received_at);

-- ---------------------------------------------------------------------
-- monitoring_rate_buckets: fixed-window ingest admission (fail-closed).
-- ---------------------------------------------------------------------
CREATE TABLE monitoring_rate_buckets (
    bucket_key       VARCHAR(64)  NOT NULL,
    window_start     TIMESTAMPTZ  NOT NULL,
    attempts         INTEGER      NOT NULL,
    last_admitted_at TIMESTAMPTZ,
    expires_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_monitoring_rate_buckets PRIMARY KEY (bucket_key),
    CONSTRAINT chk_mrb_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_monitoring_rate_buckets_expires
    ON monitoring_rate_buckets (expires_at);

COMMENT ON TABLE monitoring_rate_buckets IS
    'P4-A2/#81: PostgreSQL fixed-window rate admission for activity-event ingestion (HMAC-hashed identities).';

-- ---------------------------------------------------------------------
-- Verification — the event_type allowlist admits exactly the P4-A set;
-- no P4-B/C/D media/AI types are accepted.
-- ---------------------------------------------------------------------
DO $$
DECLARE def text;
BEGIN
    SELECT pg_get_constraintdef(oid) INTO def
    FROM pg_constraint WHERE conname = 'chk_aae_event_type';
    IF def IS NULL THEN
        RAISE EXCEPTION 'V34 verification failed: event_type CHECK constraint missing';
    END IF;
    IF def LIKE '%CAMERA%' OR def LIKE '%AI_ALERT%' OR def LIKE '%RECORDING%' OR def LIKE '%EVIDENCE%' THEN
        RAISE EXCEPTION 'V34 verification failed: media/AI event types must not be admitted';
    END IF;
END $$;
