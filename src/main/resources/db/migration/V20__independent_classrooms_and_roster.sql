-- ============================================================
-- Quizopia Flyway Migration V20 (Identity-M3, System issue #15)
-- Purpose: independent-teacher classrooms, pending roster entries
--          with verified-email linking.
--
-- Forward-only. Legacy V8/V12/V17 constraints that bind classrooms to
-- teacher_profiles/schools are RELAXED (not rewritten): independent
-- classrooms carry owner_user_id + their owner's PERSONAL workspace;
-- legacy rows are backfilled and keep their school/org semantics.
-- ============================================================

-- ============================================================
-- 1. CLASSROOMS: user-based ownership alongside legacy teacher/school
-- ============================================================
ALTER TABLE classrooms ADD COLUMN owner_user_id BIGINT;

-- Backfill from the legacy owner teacher profile.
UPDATE classrooms c
   SET owner_user_id = tp.user_id
  FROM teacher_profiles tp
 WHERE tp.id = c.owner_teacher_id
   AND tp.school_id = c.school_id
   AND c.owner_user_id IS NULL;

ALTER TABLE classrooms ALTER COLUMN owner_user_id SET NOT NULL;

ALTER TABLE classrooms
    ADD CONSTRAINT fk_classrooms_owner_user
        FOREIGN KEY (owner_user_id) REFERENCES users (id) ON DELETE RESTRICT;

CREATE INDEX idx_classrooms_owner_user
    ON classrooms (owner_user_id, created_at);

-- Relax the legacy composite FKs: independent classrooms have neither a
-- school nor a teacher_profile.
ALTER TABLE classrooms DROP CONSTRAINT fk_classrooms_teacher_school;
ALTER TABLE classrooms DROP CONSTRAINT fk_classrooms_school;
ALTER TABLE classrooms ALTER COLUMN school_id DROP NOT NULL;
ALTER TABLE classrooms ALTER COLUMN owner_teacher_id DROP NOT NULL;

-- Exactly one ownership mode per classroom: legacy (school + teacher
-- profile) OR independent (owner user, no school).
ALTER TABLE classrooms ADD CONSTRAINT chk_classrooms_ownership_mode CHECK (
    (school_id IS NOT NULL AND owner_teacher_id IS NOT NULL)
    OR
    (school_id IS NULL AND owner_teacher_id IS NULL)
);

-- Owner-scoped unique code across BOTH modes (replaces the school-scoped
-- legacy index; NULL school rows never collide with legacy rows because
-- NULLs are distinct in unique indexes and the lower(code) column is
-- shared per owner_user_id).
DROP INDEX IF EXISTS uk_classrooms_owner_code_ci;
CREATE UNIQUE INDEX uk_classrooms_owner_user_code_ci
    ON classrooms (owner_user_id, LOWER(code));

-- Independent classrooms must live in their owner's PERSONAL workspace;
-- legacy rows keep the ORGANIZATION workspace (enforced by data, since a
-- CHECK against another table is not possible — the service layer and
-- tests guarantee it).

-- ============================================================
-- 2. CLASSROOM_ROSTER_ENTRIES (pending invitations)
-- Email is the matching address — NEVER a user identity key. Sensitive
-- fields (dob, phones) are stored as AES-256-GCM ciphertext, encrypted
-- with the same key/versioning scheme as users.phone_encrypted.
-- ============================================================
CREATE TABLE classroom_roster_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    classroom_id BIGINT NOT NULL,

    -- Matching email (canonical: trimmed + lowercased).
    email_normalized VARCHAR(254) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    user_id BIGINT,

    -- Plain-text display fields (no privacy concern).
    full_name VARCHAR(150) NOT NULL,
    student_number VARCHAR(50),
    gender VARCHAR(10),

    -- Encrypted sensitive fields (v1: prefixed AES-256-GCM ciphertext).
    dob_encrypted TEXT,
    phone_encrypted TEXT,
    parent_phone_encrypted TEXT,
    email_encrypted TEXT,

    -- Audit trail.
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    linked_at TIMESTAMPTZ,
    left_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,

    CONSTRAINT fk_roster_entries_classroom
        FOREIGN KEY (classroom_id) REFERENCES classrooms (id) ON DELETE CASCADE,
    CONSTRAINT fk_roster_entries_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_roster_entries_creator
        FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,

    CONSTRAINT chk_roster_entries_status
        CHECK (status IN ('PENDING', 'LINKED', 'REVOKED', 'DECLINED')),

    CONSTRAINT chk_roster_entries_gender
        CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER')),

    -- LINKED entries must reference the linked user; terminal states keep
    -- the historical link for audit.
    CONSTRAINT chk_roster_entries_linking
        CHECK (
            (status IN ('LINKED', 'DECLINED') AND user_id IS NOT NULL)
            OR (status IN ('PENDING', 'REVOKED') AND user_id IS NULL)
        ),

    CONSTRAINT chk_roster_entries_email_not_blank
        CHECK (LENGTH(TRIM(email_normalized)) > 0),

    CONSTRAINT chk_roster_entries_full_name_not_blank
        CHECK (LENGTH(TRIM(full_name)) > 0),

    CONSTRAINT chk_roster_entries_encrypted_format
        CHECK (
            (dob_encrypted IS NULL OR dob_encrypted LIKE 'v1:%')
            AND (phone_encrypted IS NULL OR phone_encrypted LIKE 'v1:%')
            AND (parent_phone_encrypted IS NULL OR parent_phone_encrypted LIKE 'v1:%')
            AND (email_encrypted IS NULL OR email_encrypted LIKE 'v1:%')
        )
);

-- One ACTIVE (PENDING) invitation per (classroom, email). Re-inviting a
-- REVOKED/DECLINED address creates a NEW row (history preserved), so the
-- partial index only covers PENDING.
CREATE UNIQUE INDEX uk_roster_pending_classroom_email
    ON classroom_roster_entries (classroom_id, email_normalized)
    WHERE status = 'PENDING';

CREATE INDEX idx_roster_entries_user
    ON classroom_roster_entries (user_id)
    WHERE user_id IS NOT NULL;

CREATE INDEX idx_roster_entries_classroom
    ON classroom_roster_entries (classroom_id, status);

-- Reconciliation lookup: all pending entries for a verified email.
CREATE INDEX idx_roster_pending_email
    ON classroom_roster_entries (email_normalized)
    WHERE status = 'PENDING';
