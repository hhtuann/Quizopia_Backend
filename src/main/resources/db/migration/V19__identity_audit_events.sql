-- ============================================================
-- Quizopia Flyway Migration V19 (Identity-M2, System issue #14)
-- Purpose: audit trail for identity lifecycle decisions.
--
-- Forward-only. Records who self-upgraded to TEACHER (and when,
-- from which client) with no secrets and no PII beyond ids.
-- ============================================================

CREATE TABLE identity_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip VARCHAR(64),
    user_agent VARCHAR(500),

    -- Minimal, non-sensitive context (e.g. which roles the user had).
    details JSONB NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT fk_identity_audit_events_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_identity_audit_events_type
        CHECK (event_type IN ('TEACHER_SELF_UPGRADE', 'TEACHER_SELF_UPGRADE_IDEMPOTENT', 'TEACHER_SELF_UPGRADE_REACTIVATED'))
);

CREATE INDEX idx_identity_audit_events_user
    ON identity_audit_events (user_id, created_at DESC);
