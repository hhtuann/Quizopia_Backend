-- ============================================================
-- Quizopia Flyway Migration V18 (Identity-M1, System issue #13)
-- Purpose: email OTP verification, Google OIDC external
--          identities, one-time OAuth exchange codes.
--
-- Forward-only. Does not touch V1–V17 objects except adding a
-- nullable column to users.
-- ============================================================

-- ============================================================
-- 1. USERS: email verification state
-- NULL  = not verified (all accounts registered after M1 start
--         here and must verify an OTP before login).
-- SET   = verified (legacy accounts are grandfathered below at
--         their created_at — see ADR-002 §6).
-- ============================================================
ALTER TABLE users
    ADD COLUMN email_verified_at TIMESTAMPTZ;

-- Legacy compatibility: every account that existed before M1 was
-- created under a contract that did not require verification.
-- Grandfather them as verified at their creation time so no
-- existing login breaks. Runs exactly once, for pre-V18 rows only.
UPDATE users
   SET email_verified_at = created_at
 WHERE email_verified_at IS NULL;

CREATE INDEX idx_users_email_verified_at
    ON users (email_verified_at)
    WHERE email_verified_at IS NULL;

-- ============================================================
-- 2. EMAIL_VERIFICATION_CHALLENGES
-- One active (PENDING) OTP challenge per user+purpose. The OTP is
-- stored only as HMAC-SHA256 hex; the plaintext exists solely in
-- the outgoing mail. Resending supersedes the previous challenge.
-- ============================================================
CREATE TABLE email_verification_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    purpose VARCHAR(50) NOT NULL,

    otp_hash VARCHAR(64) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    failed_attempts INTEGER NOT NULL DEFAULT 0,

    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    superseded_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,

    request_ip VARCHAR(64),
    delivered BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_email_challenges_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_email_challenges_purpose
        CHECK (purpose IN ('ACCOUNT_VERIFICATION')),

    CONSTRAINT chk_email_challenges_status
        CHECK (status IN ('PENDING', 'CONSUMED', 'SUPERSEDED', 'FAILED')),

    CONSTRAINT chk_email_challenges_otp_hash
        CHECK (otp_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_email_challenges_attempts
        CHECK (failed_attempts >= 0),

    CONSTRAINT chk_email_challenges_expiry
        CHECK (expires_at > created_at),

    CONSTRAINT chk_email_challenges_consumed
    CHECK (
        (status = 'CONSUMED' AND consumed_at IS NOT NULL)
        OR (status <> 'CONSUMED' AND consumed_at IS NULL)
    ),

    CONSTRAINT chk_email_challenges_superseded
    CHECK (
        (status = 'SUPERSEDED' AND superseded_at IS NOT NULL)
        OR (status <> 'SUPERSEDED' AND superseded_at IS NULL)
    ),

    CONSTRAINT chk_email_challenges_failed
    CHECK (
        (status = 'FAILED' AND failed_at IS NOT NULL)
        OR (status <> 'FAILED' AND failed_at IS NULL)
    )
);

-- At most one PENDING challenge per user+purpose: a resend first
-- supersedes the old row, then inserts the new one.
CREATE UNIQUE INDEX uk_email_challenges_pending
    ON email_verification_challenges (user_id, purpose)
    WHERE status = 'PENDING';

CREATE INDEX idx_email_challenges_user
    ON email_verification_challenges (user_id);

-- Rate limiting by creation recency (email side joins through users).
CREATE INDEX idx_email_challenges_created_ip
    ON email_verification_challenges (request_ip, created_at);

CREATE INDEX idx_email_challenges_cleanup
    ON email_verification_challenges (expires_at)
    WHERE status = 'PENDING';

-- ============================================================
-- 3. EXTERNAL_IDENTITIES
-- Stable mapping of an external OIDC identity to a Quizopia user.
-- Business key: (provider, issuer, subject). Email is recorded for
-- audit only and is NEVER part of the key (ADR-002 §3).
-- ============================================================
CREATE TABLE external_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    provider VARCHAR(50) NOT NULL,

    issuer VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,

    email_at_link VARCHAR(254),
    email_verified_at_link BOOLEAN NOT NULL DEFAULT FALSE,

    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,

    CONSTRAINT uk_external_identities_subject
        UNIQUE (provider, issuer, subject),

    CONSTRAINT fk_external_identities_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_external_identities_provider
        CHECK (provider IN ('GOOGLE')),

    CONSTRAINT chk_external_identities_issuer_not_blank
        CHECK (LENGTH(TRIM(issuer)) > 0),

    CONSTRAINT chk_external_identities_subject_not_blank
        CHECK (LENGTH(TRIM(subject)) > 0)
);

CREATE INDEX idx_external_identities_user
    ON external_identities (user_id);

-- ============================================================
-- 4. OAUTH_LOGIN_CODES
-- Single-use, short-lived opaque codes produced by the OIDC login
-- success handler and exchanged by the SPA at
-- POST /api/auth/oauth/exchange. Only a SHA-256 hash is stored so
-- a database leak cannot mint sessions (ADR-002 §4).
-- ============================================================
CREATE TABLE oauth_login_codes (
    id UUID PRIMARY KEY,

    user_id BIGINT NOT NULL,
    code_hash VARCHAR(64) NOT NULL,

    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_oauth_login_codes_hash
        UNIQUE (code_hash),

    CONSTRAINT fk_oauth_login_codes_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_oauth_login_codes_hash
        CHECK (code_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_oauth_login_codes_expiry
        CHECK (expires_at > created_at),

    CONSTRAINT chk_oauth_login_codes_consumed
        CHECK (consumed_at IS NULL OR consumed_at >= created_at)
);

CREATE INDEX idx_oauth_login_codes_user
    ON oauth_login_codes (user_id);
