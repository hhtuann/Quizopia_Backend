-- =====================================================================
-- V28 (community bookmarks, ADR-006 §3 V28 / §7, issue #45):
--
--   * community_bookmarks — the per-user saved shelf. One row per
--     (user, publication) via UNIQUE, immutable after insert (no
--     UPDATE path exists: rows are created by the idempotent
--     ON CONFLICT DO NOTHING upsert and removed by DELETE).
--
-- V1–V27 are untouched; this migration only ADDS one table and indexes.
-- FK policy (ADR-006 §3): user_id RESTRICTs (no user hard-delete path
-- exists), publication_id CASCADEs — a bookmark's meaning dies with the
-- publication.
-- =====================================================================

CREATE TABLE community_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    publication_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_community_bookmarks_user_publication UNIQUE (user_id, publication_id),

    CONSTRAINT fk_community_bookmarks_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_bookmarks_publication
        FOREIGN KEY (publication_id) REFERENCES community_publications (id) ON DELETE CASCADE
);

-- Owner scan: GET /api/community/me/bookmarks
-- (created_at DESC, id DESC — ADR-006 §7).
CREATE INDEX idx_community_bookmarks_owner
    ON community_bookmarks (user_id, created_at DESC, id DESC);

-- ---------------------------------------------------------------------
-- Verification — the bookmark contract holds.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uk_community_bookmarks_user_publication'
    ) THEN
        RAISE EXCEPTION 'V28 verification: bookmark unique constraint missing';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE indexname = 'idx_community_bookmarks_owner'
    ) THEN
        RAISE EXCEPTION 'V28 verification: bookmark owner index missing';
    END IF;
    RAISE NOTICE 'V28: community bookmarks complete';
END $$;
