-- =====================================================================
-- V29 (community fork records, ADR-006 §3 V29 / §7-§8, issue #47):
--
--   * community_fork_records — the cross-user fork ledger. One row per
--     successful fork: (actor, idempotency key) is UNIQUE so a retried
--     request can only ever map to one target exam, and target_exam_id
--     is UNIQUE because one DRAFT target is created per fork.
--
-- V1–V28 are untouched; this migration only ADDS one table and its
-- constraints. FK policy (ADR-006 §3): every FK here is ON DELETE
-- RESTRICT — actor/source/target rows must never silently disappear
-- from under the ledger (no user or exam hard-delete path exists).
--
-- idempotency_key_hash is the server-keyed HMAC-SHA-256 of
-- `community-fork:<actor_user_id>:<key>` (ADR-006 §3/§9 key posture:
-- derived from the configured data encryption key under the distinct
-- domain `quizopia.community.fork.v1`); the plaintext key is never
-- stored. The CHECK pins the storage shape: exactly 64 lowercase hex.
-- =====================================================================

CREATE TABLE community_fork_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_user_id BIGINT NOT NULL,
    idempotency_key_hash VARCHAR(64) NOT NULL,

    source_publication_id BIGINT NOT NULL,
    source_exam_id BIGINT NOT NULL,
    target_exam_id BIGINT NOT NULL,

    source_title_snapshot VARCHAR(255),
    source_alias_snapshot VARCHAR(80),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_community_fork_records_key_hex
        CHECK (idempotency_key_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT uk_community_fork_records_actor_key
        UNIQUE (actor_user_id, idempotency_key_hash),
    CONSTRAINT uk_community_fork_records_target_exam
        UNIQUE (target_exam_id),

    CONSTRAINT fk_community_fork_records_actor
        FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_fork_records_source_publication
        FOREIGN KEY (source_publication_id) REFERENCES community_publications (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_fork_records_source_exam
        FOREIGN KEY (source_exam_id) REFERENCES exams (id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_fork_records_target_exam
        FOREIGN KEY (target_exam_id) REFERENCES exams (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- Verification — the fork contract holds.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uk_community_fork_records_actor_key'
    ) THEN
        RAISE EXCEPTION 'V29 verification: fork idempotency unique constraint missing';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uk_community_fork_records_target_exam'
    ) THEN
        RAISE EXCEPTION 'V29 verification: fork target unique constraint missing';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_community_fork_records_key_hex'
    ) THEN
        RAISE EXCEPTION 'V29 verification: idempotency key hex CHECK missing';
    END IF;
    RAISE NOTICE 'V29: community fork records complete';
END $$;
