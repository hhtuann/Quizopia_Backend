/**
 * D3 (issue #93) REAL extraction path: real ffmpeg binary + real MinIO —
 * the same pipeline the e2e run exercises. Two genuine MP4 segments are
 * GENERATED by ffmpeg (lavfi testsrc, 640x360, h264, 4s each), stored in
 * MinIO, referenced by rolling job rows, and the produced clip is verified
 * by ffprobe (duration ≈ the requested window, stream codec h264).
 *
 * <p>Skipped with an explicit assumption when ffmpeg is not on PATH (local
 * dev without it); CI images ship ffmpeg. A skip is NOT a pass — the e2e
 * browser gate repeats this path against the dev stack regardless.
 */
@SpringBootTest
@ActiveProfiles("test")
@Import({PostgresTestContainerConfiguration.class, TestClockConfig.class,
        MinioTestContainerConfiguration.class})
class EvidenceClipRealFfmpegIntegrationTests {

    /** Absolute override via -Dffmpeg.path=... or plain PATH lookup. */
    static final String FFMPEG = System.getProperty("ffmpeg.path", "ffmpeg");
    private static final String FFPROBE = System.getProperty("ffprobe.path", "ffprobe");

    @org.springframework.test.context.DynamicPropertySource
    static void ffmpegProperty(org.springframework.test.context.DynamicPropertyRegistry registry) {
        registry.add("quizopia.media.egress.ffmpeg-command", () -> FFMPEG);
        // tight window keeps the fixture segments short and deterministic
        registry.add("quizopia.media.egress.clip-pre-roll", () -> "5s");
        registry.add("quizopia.media.egress.clip-post-roll", () -> "5s");
    }

    @BeforeAll
    static void probeTools() {
        Assumptions.assumeTrue(canRun(FFMPEG, "-version"),
                "ffmpeg unavailable — real-extraction test skipped (not a pass)");
        Assumptions.assumeTrue(canRun(FFPROBE, "-version"),
                "ffprobe unavailable — real-extraction test skipped (not a pass)");
    }

    private static boolean canRun(String... command) {
        try {
            Process p = new ProcessBuilder(command).start();
            p.getErrorStream().readAllBytes();
            return p.waitFor(15, java.util.concurrent.TimeUnit.SECONDS) && p.exitValue() == 0;
        } catch (Exception e) {
            return false;
        }
    }

    @Autowired private ClipService clips;
    @Autowired private EvidenceStorage storage;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private MutableClock clock;

    private Instant base;
    private long teacherId;
    private long sessionId;
    private long attemptId;
    private long alertId;
    private UUID bindingId;

    @BeforeEach
    void setUp() {
        base = Instant.parse("2026-11-15T08:00:00Z");
        clock.setInstant(base);
        String sfx = UUID.randomUUID().toString().substring(0, 8);
        teacherId = newTeacherUser(jdbc, "rffteacher" + sfx);
        long studentId = newUser(jdbc, "rffstudent" + sfx);
        sessionId = insertOpenSession(jdbc, teacherId, base);
        attemptId = jdbc.queryForObject(
                "INSERT INTO attempts (exam_session_id, user_id, attempt_number, status, "
                        + "started_at, deadline_at) VALUES (?,?,1,'IN_PROGRESS',?,?) RETURNING id",
                Long.class, sessionId, studentId,
                java.sql.Timestamp.from(base), java.sql.Timestamp.from(base.plusSeconds(3600)));
        alertId = jdbc.queryForObject(
                "INSERT INTO monitoring_ai_alerts (attempt_id, exam_session_id, user_id, "
                        + "alert_type, status, first_detected_at, last_detected_at, detection_count, "
                        + "model_id, model_version, provenance) "
                        + "VALUES (?,?,?,'PHONE_DETECTED','OPEN',?,?,1,'yolo26s','8.4.64-onnx',"
                        + "'CLIENT_MODEL') RETURNING id",
                Long.class, attemptId, sessionId, studentId,
                java.sql.Timestamp.from(base), java.sql.Timestamp.from(base.plusSeconds(2)));
        bindingId = UUID.randomUUID();
        UUID preflightId = UUID.randomUUID();
        jdbc.update("INSERT INTO monitoring_preflights "
                        + "(id, exam_session_id, user_id, media_identity, status, expires_at) "
                        + "VALUES (?,?,?,?, 'VERIFIED', ?)",
                preflightId, sessionId, studentId, UUID.randomUUID().toString(),
                java.sql.Timestamp.from(base.plusSeconds(3600)));
        jdbc.update("INSERT INTO monitoring_media_bindings "
                        + "(id, exam_session_id, user_id, preflight_id, attempt_id, media_identity, epoch) "
                        + "VALUES (?,?,?,?,?,?,1)",
                bindingId, sessionId, studentId, preflightId, attemptId,
                UUID.randomUUID().toString());
    }

    @Test
    void realFfmpegCutsRealMp4SegmentsIntoVerifiedClip() throws Exception {
        enableMonitoringWithPolicy(jdbc, sessionId, false, false, true);

        // Two REAL 5-second MP4s (h264 testsrc, 1s keyframes) via ffmpeg —
        // pulse file durations match their wall-clock spans exactly so the
        // inpoint/outpoint math is physically honest.
        String key1 = "rolling/" + attemptId + "/real-1.mp4";
        String key2 = "rolling/" + attemptId + "/real-2.mp4";
        generateTestMp4(key1, 5);
        generateTestMp4(key2, 5);

        // Pulses [−6s,−1s] and [+2s,+7s]: a REAL 3-second gap inside the
        // window [first−5s, last+5s] = [−5s, +7s] → honest PARTIAL clip.
        insertRollingPulse("EG_RFF_1", base.minusSeconds(6), base.minusSeconds(1), key1);
        insertRollingPulse("EG_RFF_2", base.plusSeconds(2), base.plusSeconds(7), key2);

        MonitoringEvidence clip = clips.requestClip(teacherId, sessionId, alertId);

        assertThat(clip.getStatus()).as("real 3s gap inside the window → PARTIAL (honest)")
                .isEqualTo("PARTIAL");
        assertThat(clip.getObjectKey()).isNotNull();
        assertThat(clip.getBytes()).isGreaterThan(1000);
        assertThat(storage.head(clip.getObjectKey())).isPresent();

        // ffprobe verification of the produced clip: h264 stream; covered
        // parts are [−5,−1]=4s and [+2,+7]=5s → ~9s ± keyframe slack.
        String out = new String(ffprobe(clip.getObjectKey()));
        assertThat(out).contains("h264");
        assertThat(extractDuration(out)).isBetween(7.0, 12.0);
        assertThat(clip.getCoverageJson()).contains("\"gaps\"")
                .contains("\"from\":\"2026-11-15T07:59:59Z\"");
    }

    private void generateTestMp4(String objectKey, int seconds) throws Exception {
        java.nio.file.Path tmp = java.nio.file.Files.createTempFile("rff", ".mp4");
        Process p = new ProcessBuilder(FFMPEG, "-nostdin", "-loglevel", "error", "-y",
                "-f", "lavfi", "-i", "testsrc=size=640x360:rate=25:duration=" + seconds,
                "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
                "-g", "25", "-force_key_frames", "expr:gte(t,n_forced*1)",
                tmp.toString()).start();
        p.getErrorStream().readAllBytes();
        assertThat(p.waitFor(60, java.util.concurrent.TimeUnit.SECONDS)).isTrue();
        assertThat(p.exitValue()).as("ffmpeg segment generation failed").isZero();
        byte[] bytes = java.nio.file.Files.readAllBytes(tmp);
        storage.put(objectKey, bytes, "video/mp4");
        java.nio.file.Files.delete(tmp);
    }

    private byte[] ffprobe(String objectKey) throws Exception {
        java.nio.file.Path tmp = java.nio.file.Files.createTempFile("rff-probe", ".mp4");
        java.nio.file.Files.write(tmp, readFromStorage(objectKey));
        Process p = new ProcessBuilder(FFPROBE, "-v", "error", "-show_entries",
                "stream=codec_name:format=duration", "-of", "default=noprint_wrappers=1",
                tmp.toString()).start();
        byte[] out = p.getInputStream().readAllBytes();
        p.getErrorStream().readAllBytes();
        assertThat(p.waitFor(30, java.util.concurrent.TimeUnit.SECONDS)).isTrue();
        assertThat(p.exitValue()).as("ffprobe failed — clip not a valid MP4").isZero();
        java.nio.file.Files.delete(tmp);
        return out;
    }

    private byte[] readFromStorage(String objectKey) {
        // EvidenceStorage port has no GET; use presigned URL download.
        String url = storage.presignedGet(objectKey, java.time.Duration.ofSeconds(60));
        try (java.io.InputStream in = new java.net.URL(url).openStream();
             java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream()) {
            in.transferTo(out);
            return out.toByteArray();
        } catch (Exception e) {
            throw new IllegalStateException("storage GET failed: " + e.getMessage(), e);
        }
    }

    private void insertRollingPulse(String egressId, Instant from, Instant to, String objectKey) {
        jdbc.update("INSERT INTO monitoring_recording_jobs "
                        + "(id, exam_session_id, attempt_id, binding_id, kind, egress_id, room_name, "
                        + "track_sid, status, pulse_index, started_at, ended_at, object_key, bytes, duration_ms) "
                        + "VALUES (?,?,?,?,?,?,?,?,'COMPLETE',0,?,?,?,?,?)",
                UUID.randomUUID(), sessionId, attemptId, bindingId, "ROLLING", egressId,
                "room-rff", "TR_RFF", java.sql.Timestamp.from(from), java.sql.Timestamp.from(to),
                objectKey, 50_000L,
                java.time.Duration.between(from, to).toMillis());
    }

    private static double extractDuration(String ffprobeOutput) {
        for (String line : ffprobeOutput.split("\\R")) {
            if (line.startsWith("duration=")) {
                return Double.parseDouble(line.substring("duration=".length()).trim());
            }
        }
        return -1;
    }
}
